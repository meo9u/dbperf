#!/usr/bin/env python3
"""Generate benchmark/scenarios/lib/checkout_templates.json: the order templates and customers used by the checkout
scenarios, identical for MySQL and MongoDB (their ids share the same numbering: orders._id suffix = order_id).

A template is an existing delivered order with at most 3 lines; a checkout re-places its lines (SKU, warehouse,
quantity, price snapshot) as a new pending order. "Hot" templates contain at least one of the HOT_SKUS most ordered
SKUs, so they contend for the same inventory rows; "cold" templates come from a fixed id range. Regenerate the file
whenever the dataset changes.

Usage: python3 benchmark/checkout_templates.py [--hot-skus 200] [--per-pool 500] [--customers 2000]
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_class1 import ROOT, mysql  # noqa: E402

OUT = ROOT / "benchmark" / "scenarios" / "lib" / "checkout_templates.json"


def column(sql):
    return [int(l) for l in mysql(sql, "-N").split("\n") if l.strip()]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--hot-skus", type=int, default=200)
    ap.add_argument("--per-pool", type=int, default=500)
    ap.add_argument("--customers", type=int, default=2000)
    a = ap.parse_args()
    hot_skus = column(f"SELECT sku_id FROM order_detail GROUP BY sku_id ORDER BY COUNT(*) DESC, sku_id LIMIT {a.hot_skus};")
    in_list = ",".join(map(str, hot_skus))
    short = "(SELECT COUNT(*) FROM order_detail x WHERE x.order_id = o.order_id) <= 3"
    hot = column(f"SELECT o.order_id FROM orders o WHERE o.status = 'delivered' AND {short} "
                 f"AND EXISTS (SELECT 1 FROM order_detail d WHERE d.order_id = o.order_id AND d.sku_id IN ({in_list})) "
                 f"ORDER BY o.order_id LIMIT {a.per_pool};")
    cold = column(f"SELECT o.order_id FROM orders o WHERE o.order_id BETWEEN 100001 AND 300000 AND o.status = 'delivered' "
                  f"AND {short} ORDER BY o.order_id LIMIT {a.per_pool};")
    customers = column(f"SELECT customer_id FROM customer WHERE phone IS NOT NULL ORDER BY customer_id LIMIT {a.customers};")
    data = {"hot_skus": hot_skus, "hot": hot, "cold": cold, "customers": customers,
            "note": "generated by benchmark/checkout_templates.py from the loaded dataset"}
    OUT.write_text(json.dumps(data) + "\n", encoding="utf-8")
    print(f"hot skus {len(hot_skus)}, hot templates {len(hot)}, cold templates {len(cold)}, customers {len(customers)} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
